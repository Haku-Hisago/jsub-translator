def _user_glossary_path() -> Path:
    """用户覆盖词典的位置（打包版=exe 同目录，开发版=项目根）。"""
    if getattr(sys, "frozen", False):
        return Path(sys.executable).parent / "jpop_glossary.json"
    return Path(__file__).resolve().parent.parent / "jpop_glossary.json"


def load_glossary() -> dict:
    """内置词典 + 外部 jpop_glossary.json 覆盖（用户条目优先）。"""
    merged = dict(JPOP_GLOSSARY)
    path = _user_glossary_path()
    try:
        if path.exists():
            data = json.loads(path.read_text(encoding="utf-8"))
            if isinstance(data, dict):
                merged.update(data)
    except Exception:
        pass  # 用户词典损坏时静默忽略，回退到内置词典
    return merged


# 翻译时实际使用的合并词典
GLOSSARY = load_glossary()


def build_glossary_hint(source_text: str, glossary: dict = None) -> str:
    """
    从源文本中找出命中的术语，生成提示词片段。

    无命中时返回空字符串（不向请求注入任何内容）。
    """
    glossary = glossary or GLOSSARY
    hits = {k: v for k, v in glossary.items() if k in source_text}
    if not hits:
        return ""
    lines = [f"{k} → {v}" for k, v in hits.items()]
    return "术语参考（优先采用以下译法）：\n" + "\n".join(lines)
